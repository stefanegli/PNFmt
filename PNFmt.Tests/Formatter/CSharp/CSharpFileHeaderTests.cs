        [Fact]
        public void Public_formatter_resolves_templates_preserves_encoding_and_supports_preview()
        {
            using (var directory = new TestDirectory())
            {
                directory.Write(".editorconfig", "root = true\n[*.cs]\npnfmt_enabled = true\npnfmt_formatter = csharp\n"
                    + "file_header_template = Copyright {fileName}\\nAll rights reserved.\nend_of_line = lf\n");
                var path = directory.GetPath("Sample.cs");
                const string Input = "class C{ }";
                File.WriteAllText(path, Input, new UnicodeEncoding(false, true));
                var original = File.ReadAllBytes(path);
                var formatter = new CSharpFormatter();
                Assert.Equal(FileFormatStatus.Updated, formatter.Format(new FileFormatRequest(path, false, false, NullFormatterLog.Instance)).Status);
                Assert.Equal(original, File.ReadAllBytes(path));
                Assert.Equal(FileFormatStatus.Updated, formatter.Format(new FileFormatRequest(path, true, false, NullFormatterLog.Instance)).Status);
                Assert.Equal("// Copyright Sample.cs\n// All rights reserved.\n\nclass C { }", File.ReadAllText(path));
                Assert.Equal(new byte[] { 0xff, 0xfe }, File.ReadAllBytes(path).Take(2));
                Assert.Equal(FileFormatStatus.Unchanged, formatter.Format(new FileFormatRequest(path, true, false, NullFormatterLog.Instance)).Status);
            }
        }

        [Fact]
        public void Replaces_filename_placeholders_with_the_actual_basename()
        {
            Assert.Equal("// Sample.cs belongs here: Sample.cs\n\nclass C { }",
                Format("class C { }", "{fileName} belongs here: {fileName}", Path.Combine("nested", "Sample.cs")));
        }

        [Fact]
        public void Supports_multiline_templates_blank_comment_lines_and_literal_backslashes()
        {
            Assert.Equal("// Copyright\n//\n// Path C:\\tools; severity:warning\n\nclass C { }",
                Format("class C { }", "Copyright\\n\\nPath C:\\tools; severity:warning  "));
            const string Existing = "/* Copyright\n * Second line\n */\nclass C { }";
            Assert.Equal(CSharpFormatterTests.Format(Existing), Format(Existing, "Copyright\\nSecond line"));
        }

        [Fact]
        public void Templates_do_not_activate_file_processing_and_can_be_unset_in_child_configuration()
        {
            using (var directory = new TestDirectory())
            {
                directory.Write(".editorconfig", "root = true\n[*.cs]\nfile_header_template = License\n");
                var path = directory.Write("Sample.cs", "class C{ }");
                var formatter = new CSharpFormatter();
                Assert.Equal(FileFormatStatus.Skipped, formatter.Format(new FileFormatRequest(path, true, false, NullFormatterLog.Instance)).Status);
                directory.Write("nested/.editorconfig", "[*.cs]\npnfmt_enabled = true\npnfmt_formatter = csharp\nfile_header_template = unset\n");
                path = directory.Write("nested/Other.cs", "class C{ }");
                Assert.Equal(FileFormatStatus.Updated, formatter.Format(new FileFormatRequest(path, true, false, NullFormatterLog.Instance)).Status);
                Assert.Equal("class C { }", File.ReadAllText(path));
            }
        }

        [Theory]
        [InlineData("lf", "\n")]
        [InlineData("crlf", "\r\n")]
        [InlineData("cr", "\r")]
        public void Uses_configured_or_detected_newlines_and_preserves_eof(string style, string newline)
        {
            var options = new[] { ("end_of_line", style) };
            Assert.Equal("// First" + newline + "// Second" + newline + newline + "class C { }",
                Format("class C { }", "First\\nSecond", options: options));
            Assert.Equal("// License" + newline + newline + "class C { }" + newline,
                Format("class C { }" + newline, "License"));
            Assert.Equal("// License" + newline + newline + "class C { }" + newline,
                Format("class C { }", "License", options: new[] { ("end_of_line", style), ("insert_final_newline", "true") }));
        }

        private static string Format(string input, string template, string filePath = "Source.cs", params (string Key, string Value)[] options)
        {
            var settings = options.ToDictionary(option => option.Key, option => option.Value);
            if (template is not null)
            {
                settings["file_header_template"] = template;
            }
            var result = CSharpDocumentFormatter.Format(input, settings, out var diagnostic, filePath);
            Assert.Null(diagnostic);
            Assert.Equal(result, CSharpDocumentFormatter.Format(result, settings, out diagnostic, filePath));
            Assert.Null(diagnostic);
            if (!settings.ContainsKey("pnfmt_sort_entries"))
            {
                Assert.Equal(CSharpSyntaxTree.ParseText(input).GetRoot().DescendantTokens().Select(token => token.Text),
                    CSharpSyntaxTree.ParseText(result).GetRoot().DescendantTokens().Select(token => token.Text));
            }
            return result;
        }
