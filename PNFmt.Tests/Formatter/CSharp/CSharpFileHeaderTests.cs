        [Theory]
        [InlineData("#nullable enable\nclass C { }", "// License\n\n#nullable enable\nclass C { }")]
        [InlineData("#nullable enable\n// Old\nclass C { }", "#nullable enable\n// License\n\nclass C { }")]
        [InlineData("#if FEATURE\n// Inactive\nclass D{}\n#endif\nclass C { }", "// License\n\n#if FEATURE\n// Inactive\nclass D{}\n#endif\nclass C { }")]
