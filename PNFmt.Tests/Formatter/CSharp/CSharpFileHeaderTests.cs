using System;
using System.IO;
using System.Linq;
using System.Text;

using Microsoft.CodeAnalysis.CSharp;

using Xunit;

namespace PNFmt.Tests.Formatter.CSharp
{
    public sealed class CSharpFileHeaderTests
    {
        [Theory]
        [InlineData("class C { }", "// License\n\nclass C { }")]
        [InlineData("\n\nclass C { }\n", "// License\n\nclass C { }\n")]
        [InlineData("// Old\n// Header\n\nclass C { }", "// License\n\nclass C { }")]
        [InlineData("// Old\nclass C { }", "// License\n\nclass C { }")]
        [InlineData("/* Old\n * Header\n */\nclass C { }", "// License\n\nclass C { }")]
        [InlineData("/* Old */ class C { }", "// License\n\nclass C { }")]
        [InlineData("// Old\n\n// Explanation\nclass C { }", "// License\n\n// Explanation\nclass C { }")]
        [InlineData("// Old\n\n \n// Explanation\nclass C { }", "// License\n\n// Explanation\nclass C { }")]
        [InlineData("/// <summary>C</summary>\nclass C { }", "// License\n\n/// <summary>C</summary>\nclass C { }")]
        [InlineData("/** <summary>C</summary> */\nclass C { }", "// License\n\n/** <summary>C</summary> */\nclass C { }")]
        [InlineData("// Old\n/// <summary>C</summary>\nclass C { }", "// License\n\n/// <summary>C</summary>\nclass C { }")]
        public void Adds_or_updates_the_leading_header_and_preserves_later_comments(string input, string expected)
        {
            Assert.Equal(expected, Format(input, "License"));
        }

        [Theory]
        [InlineData("pnfmt_format")]
        [InlineData("pnfmt_csharp_format")]
        public void Disabled_layout_does_not_apply_headers(string setting)
        {
            const string Input = "class C{ }";
            Assert.Equal(Input, Format(Input, "License", options: new[] { (setting, "false") }));
        }

        [Fact]
        public void Empty_file_honors_explicit_final_newline()
        {
            Assert.Equal("// License\n", Format("", "License", options: new[] { ("end_of_line", "lf"), ("insert_final_newline", "true") }));
        }

        [Theory]
        [InlineData("// pnfmt: off\nclass C{ }\n// pnfmt: on\n")]
        [InlineData("// pnfmt: off\nclass C{ }")]
        [InlineData("// pnfmt: off\n// Old\n// pnfmt: on\nclass C { }\n")]
        public void Excluded_headers_and_opening_markers_are_preserved(string input)
        {
            Assert.Equal(input, Format(input, "License"));
        }

        [Theory]
        [InlineData("Sample.g.cs", "class C{ }")]
        [InlineData("Sample.cs", "// <auto-generated/>\nclass C{ }")]
        [InlineData("Sample.cs", "class C {")]
        public void Generated_and_invalid_files_are_skipped_before_header_replacement(string name, string input)
        {
            using (var directory = new TestDirectory())
            {
                directory.Write(".editorconfig", "root = true\n[*.cs]\npnfmt_enabled = true\npnfmt_formatter = csharp\nfile_header_template = License\n");
                var path = directory.Write(name, input);
                Assert.Equal(FileFormatStatus.Skipped, new CSharpFormatter().Format(new FileFormatRequest(path, true, false, NullFormatterLog.Instance)).Status);
                Assert.Equal(input, File.ReadAllText(path));
            }
        }

        [Theory]
        [InlineData("", "// License")]
        [InlineData("\n\n", "// License\n")]
        [InlineData("// Old", "// License")]
        [InlineData("/* Old */\n", "// License\n")]
        public void Handles_empty_and_comment_only_files(string input, string expected)
        {
            Assert.Equal(expected, Format(input, "License"));
        }

        [Fact]
        public void Header_templates_compose_with_sorting_wrapping_and_blank_line_preferences()
        {
            const string Input = "// Old\nusing Z; using A;\nclass C { static public void M(int x, int y) { } }";
            var result = Format(Input, "License", options: new[]
            {
                ("pnfmt_sort_entries", "true"), ("pnfmt_csharp_sort_modifiers", "true"),
                ("pnfmt_csharp_sort_members", "true"), ("csharp_wrap_parameters_style", "chop_always"),
                ("dotnet_style_allow_multiple_blank_lines_experimental", "false"),
                ("csharp_style_allow_blank_lines_between_consecutive_braces_experimental", "false"),
                ("dotnet_style_allow_statement_immediately_after_block_experimental", "false"),
            });
            Assert.StartsWith("// License\n\nusing A;\nusing Z;", result);
            Assert.Contains("public static void M(\n", result);
        }

        [Theory]
        [InlineData("// pnfmt: on\nclass C { }", "// License\n\n// pnfmt: on\nclass C { }")]
        [InlineData("// Old\n// pnfmt: off\nclass C{ }\n// pnfmt: on\n", "// License\n\n// pnfmt: off\nclass C{ }\n// pnfmt: on\n")]
        public void Headers_can_precede_exclusions_without_consuming_markers(string input, string expected)
        {
            Assert.Equal(expected, Format(input, "License"));
        }

